# Starts Trend & Tend Server in one of two modes:
#
#   built-in database (default): runs PostgreSQL inside this container, with
#     its data in /data/postgres. Nothing else to set up.
#   external database: when DATABASE_URL is set, uses that PostgreSQL instead
#     and starts no database here. docker-compose.prod.yml does this, with
#     the official postgres image.
#
# Then applies migrations and runs the API and nginx. If any server process
# exits, the others are stopped and the container exits non-zero, so
# Docker's restart policy takes over rather than leaving a half-working
# server up.
set -euo pipefail

log() { echo "[trend-tend] $*"; }
die() { echo "[trend-tend] ERROR: $*" >&2; exit 1; }

DATA=/data
SECRETS="$DATA/secrets.env"
ATTACHMENTS="$DATA/attachments"

# Started as root only to fix ownership under /data: a host bind mount, or
# a volume written by an older image (1.0.x's API container ran as uid
# 10001). Then drop to the unprivileged postgres user (uid 999) for
# everything else, with tini as PID 1 to reap and forward signals.
if [[ "$(id -u)" == 0 ]]; then
    mkdir -p "$DATA"
    find "$DATA" \! -user postgres -exec chown -h postgres:postgres {} +
    exec gosu postgres tini -s -- "$0" "$@"
fi
[[ $$ == 1 ]] && exec tini -s -- "$0" "$@"

[[ -w "$DATA" ]] || die "$DATA is not writable by uid $(id -u). If you bind-mount a host directory, chown it to 999:999, or let the container start as root so it can fix this itself."

if [[ -n "${DATABASE_URL:-}" ]]; then MODE=external; else MODE=builtin; fi

# --- Secrets ---------------------------------------------------------------
# Anything not given in the environment is generated once and kept in
# /data/secrets.env (mode 600), so restarts reuse it. Environment values
# always win, so `-e JWT_SECRET=...` or a Compose .env still decide.
touch "$SECRETS" && chmod 600 "$SECRETS"
while IFS='=' read -r key value; do
    [[ -z "$key" || "$key" == \#* ]] && continue
    [[ -z "${!key:-}" ]] && export "$key=$value"
done < "$SECRETS"

needed=(APP_DB_PASSWORD JWT_SECRET)
[[ "$MODE" == builtin ]] && needed=(POSTGRES_PASSWORD "${needed[@]}")
for key in "${needed[@]}"; do
    if [[ -z "${!key:-}" ]]; then
        log "generating $key (kept in $SECRETS)"
        value="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
        [[ -s "$SECRETS" ]] || echo "# Generated by Trend & Tend Server. Back this file up with the rest of /data." >> "$SECRETS"
        echo "$key=$value" >> "$SECRETS"
        export "$key=$value"
    fi
done

# --- Database ----------------------------------------------------------------
pg_pid=""
if [[ "$MODE" == builtin ]]; then
    if [[ -s "$PGDATA/PG_VERSION" ]]; then
        have="$(cat "$PGDATA/PG_VERSION")"
        [[ "$have" == "$PG_MAJOR" ]] || die "the database in $PGDATA was created by PostgreSQL $have, but this image runs PostgreSQL $PG_MAJOR. Nothing has been changed. Go back to the image version you were running, and see the release notes of this version for how to move your data across: https://github.com/wrinklebyte/trend-tend-server/releases"
    else
        log "first start: creating the database"
        pwfile="$(mktemp)"
        printf '%s\n' "$POSTGRES_PASSWORD" > "$pwfile"
        initdb -D "$PGDATA" -U wrinklebyte --pwfile="$pwfile" \
            --auth-local=peer --auth-host=scram-sha-256 --encoding=UTF8 >/dev/null
        rm -f "$pwfile"
    fi

    # Only ever reachable from inside this container.
    postgres -D "$PGDATA" -c listen_addresses=127.0.0.1 -c unix_socket_directories=/var/run/postgresql &
    pg_pid=$!
    export DATABASE_URL="postgresql+asyncpg://wrinklebyte:${POSTGRES_PASSWORD}@127.0.0.1:5432/wrinklebyte"
fi

# psql/pg_isready want a plain libpq URL; the app wants the asyncpg dialect.
PSQL_URL="${DATABASE_URL/postgresql+asyncpg:/postgresql:}"
case "$DATABASE_URL" in
    postgresql+asyncpg://*) ;;
    *) die "DATABASE_URL must start with postgresql+asyncpg:// (got a different scheme)" ;;
esac
db_name="$(python3 -c 'import sys,urllib.parse; print(urllib.parse.urlsplit(sys.argv[1]).path.lstrip("/"))' "$DATABASE_URL")"

for _ in $(seq 1 60); do
    pg_isready -q -d "$PSQL_URL" && break
    if [[ -n "$pg_pid" ]]; then kill -0 "$pg_pid" 2>/dev/null || die "PostgreSQL exited during startup (see the log above)"; fi
    sleep 1
done
pg_isready -q -d "$PSQL_URL" || die "the database at DATABASE_URL did not become reachable within 60s"

if [[ "$MODE" == builtin ]]; then
    pg() { PGPASSWORD="$POSTGRES_PASSWORD" psql -h 127.0.0.1 -U wrinklebyte -d postgres -v ON_ERROR_STOP=1 "$@"; }
    if [[ "$(pg -Atc "SELECT 1 FROM pg_database WHERE datname = 'wrinklebyte'")" != "1" ]]; then
        pg -qc "CREATE DATABASE wrinklebyte OWNER wrinklebyte"
    fi
else
    # The migrations name this role and database explicitly.
    [[ "$db_name" == wrinklebyte ]] || die "DATABASE_URL must point at a database named 'wrinklebyte' (got '$db_name')"
fi

# The API queries as wrinklebyte_app, a role without superuser or BYPASSRLS,
# so row-level security applies. Its URL is derived from DATABASE_URL unless
# given explicitly.
if [[ -z "${RUNTIME_DATABASE_URL:-}" ]]; then
    RUNTIME_DATABASE_URL="$(python3 - "$DATABASE_URL" "$APP_DB_PASSWORD" <<'PY'
import sys, urllib.parse as u
url, pw = sys.argv[1], sys.argv[2]
p = u.urlsplit(url)
host = p.hostname or ""
if ":" in host: host = f"[{host}]"
netloc = f"wrinklebyte_app:{u.quote(pw, safe='')}@{host}" + (f":{p.port}" if p.port else "")
print(u.urlunsplit((p.scheme, netloc, p.path, p.query, p.fragment)))
PY
)"
    export RUNTIME_DATABASE_URL
fi

# --- API configuration -----------------------------------------------------
if [[ -z "${FRONTEND_URL:-}" ]]; then
    export FRONTEND_URL="http://localhost:8080"
    log "WARNING: FRONTEND_URL is not set; using $FRONTEND_URL. Links in password-reset and invite emails, and the mobile pairing code, will point there. Set FRONTEND_URL to the address people use to reach this server."
fi
export PUBLIC_API_URL="${PUBLIC_API_URL:-$FRONTEND_URL}"
export STORAGE_BACKEND=local_disk
export STORAGE_LOCAL_ROOT="$ATTACHMENTS"
mkdir -p "$ATTACHMENTS"

log "applying database migrations ($MODE database)"
(cd /app && alembic upgrade head)

# The migration that creates wrinklebyte_app runs once. Re-apply the current
# APP_DB_PASSWORD on every start so the role and the configured password
# can't drift apart (a regenerated secret, a changed .env).
printf "ALTER ROLE wrinklebyte_app WITH LOGIN PASSWORD :'pw';\n" \
    | psql -q -v ON_ERROR_STOP=1 -v pw="$APP_DB_PASSWORD" -d "$PSQL_URL" >/dev/null \
    || die "could not set the password of the wrinklebyte_app role. The DATABASE_URL user must own the 'wrinklebyte' database and be allowed to manage roles (the default postgres superuser is)."

# --- Run -----------------------------------------------------------------
# One uvicorn worker on purpose: the login rate limiter is in-process memory
# (see backend/app/core/rate_limit.py), so several workers would each keep
# their own buckets and multiply the effective limit.
(cd /app && exec uvicorn app.main:app --host 127.0.0.1 --port 8000) &
api_pid=$!
# nginx opens its log paths by name; after the drop from root, the
# container's own stdout/stderr pipes still belong to root, so hand nginx
# pipes owned by this user instead (they feed the container's output).
nginx -g 'daemon off;' > >(cat) 2> >(cat >&2) &
nginx_pid=$!

shutdown() {
    log "stopping"
    kill -TERM "$nginx_pid" "$api_pid" 2>/dev/null || true
    wait "$nginx_pid" "$api_pid" 2>/dev/null || true
    if [[ -n "$pg_pid" ]]; then
        # SIGINT = Postgres "fast" shutdown: clean, and quick enough for
        # `docker stop`'s default 10s grace period.
        kill -INT "$pg_pid" 2>/dev/null || true
        wait "$pg_pid" 2>/dev/null || true
    fi
}
trap 'shutdown; exit 0' TERM INT

log "ready on port 8080 ($MODE database; public URL: $FRONTEND_URL)"
set +e
# shellcheck disable=SC2086  # $pg_pid is empty in external mode
wait -n $pg_pid "$api_pid" "$nginx_pid"
status=$?
set -e
log "a server process exited unexpectedly (status $status)"
shutdown
exit 1
